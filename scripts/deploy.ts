import hre from "hardhat";
const { ethers } = hre;
import * as fs from "fs";
import * as path from "path";

async function main() {
  console.log("=========================================");
  console.log("   Booklio Smart Contract Deployment     ");
  console.log("=========================================");

  const network = await ethers.provider.getNetwork();
  const chainId = Number(network.chainId);
  const isMainnet = chainId === 677 || hre.network.name === "botchainMainnet";
  const tokenSymbol = isMainnet ? "BOT" : "BOHR";
  const explorerUrl = isMainnet ? "https://scan.botchain.ai" : "https://scan.bohr.life";
  const rpcUrl = isMainnet ? "https://rpc.botchain.ai" : "https://rpc.bohr.life";

  console.log("Target Network:", hre.network.name, `(Chain ID: ${chainId})`);
  console.log("Explorer URL:", explorerUrl);

  const [deployer] = await ethers.getSigners();
  console.log("Deployer address:", deployer.address);
  const balance = await ethers.provider.getBalance(deployer.address);
  console.log(`Deployer balance: ${ethers.formatEther(balance)} ${tokenSymbol}`);

  if (balance === 0n) {
    throw new Error(`Deployer account has 0 ${tokenSymbol}. Please fund this wallet with native tokens.`);
  }

  // Check gas fee data to ensure minimal, cost-conscious deployment
  const feeData = await ethers.provider.getFeeData();
  const currentGasPrice = feeData.gasPrice || ethers.parseUnits("20", "gwei");
  console.log(`Current Gas Price: ${ethers.formatUnits(currentGasPrice, "gwei")} gwei`);

  console.log("\nDeploying Booklio contract with optimized gas...");
  const BooklioFactory = await ethers.getContractFactory("Booklio");

  // Deploy using current network gasPrice without unnecessary markup
  const booklio = await BooklioFactory.deploy({
    gasPrice: currentGasPrice,
  });
  await booklio.waitForDeployment();

  const deployedAddress = await booklio.getAddress();
  const deployTx = booklio.deploymentTransaction();
  const txHash = deployTx?.hash;

  console.log("-----------------------------------------");
  console.log("✅ Booklio deployed successfully!");
  console.log("Contract Address:", deployedAddress);
  if (txHash) {
    console.log("Deployment Tx Hash:", txHash);
    console.log("Explorer Link:", `${explorerUrl}/tx/${txHash}`);

    // Wait for receipt to show exact gas used & fee spent
    const receipt = await deployTx?.wait(1);
    if (receipt) {
      const gasUsed = receipt.gasUsed;
      const feePaid = gasUsed * (receipt.gasPrice || currentGasPrice);
      console.log(`Gas Used: ${gasUsed.toString()} units`);
      console.log(`Total Fee Paid: ${ethers.formatEther(feePaid)} ${tokenSymbol} (ultra-low fee)`);
    }
  }
  console.log("-----------------------------------------");

  const rootDir = process.cwd();

  // 1. Export contract address and ABI for frontend integration
  const contractsDir = path.join(rootDir, "src", "contracts");
  if (!fs.existsSync(contractsDir)) {
    fs.mkdirSync(contractsDir, { recursive: true });
  }

  const addressConfig = `// Auto-generated by deploy script
export const BOOKLIO_CONTRACT_ADDRESS: \`0x\${string}\` = "${deployedAddress}" as \`0x\${string}\`;

export const BOTCHAIN_CHAIN_ID = ${chainId};
export const BOTCHAIN_RPC_URL = process.env.NEXT_PUBLIC_RPC_URL || "${rpcUrl}";
export const BOTCHAIN_EXPLORER_URL = process.env.NEXT_PUBLIC_BLOCK_EXPLORER || "${explorerUrl}";
`;
  fs.writeFileSync(path.join(contractsDir, "contractAddress.ts"), addressConfig);

  const artifactPath = path.join(rootDir, "artifacts", "contracts", "Booklio.sol", "Booklio.json");
  if (fs.existsSync(artifactPath)) {
    const artifact = JSON.parse(fs.readFileSync(artifactPath, "utf8"));
    fs.writeFileSync(
      path.join(contractsDir, "BooklioABI.json"),
      JSON.stringify(artifact.abi, null, 2)
    );
  }
  console.log("Updated src/contracts/contractAddress.ts & BooklioABI.json");

  // 2. Update .env and .env.local
  const envFiles = [".env", ".env.local"];
  for (const file of envFiles) {
    const p = path.join(rootDir, file);
    if (fs.existsSync(p)) {
      let content = fs.readFileSync(p, "utf8");
      content = content.replace(
        /NEXT_PUBLIC_BOOKLIO_CONTRACT_ADDRESS=.*/,
        `NEXT_PUBLIC_BOOKLIO_CONTRACT_ADDRESS=${deployedAddress}`
      );
      content = content.replace(
        /NEXT_PUBLIC_CHAIN_ID=.*/,
        `NEXT_PUBLIC_CHAIN_ID=${chainId}`
      );
      content = content.replace(
        /NEXT_PUBLIC_RPC_URL=.*/,
        `NEXT_PUBLIC_RPC_URL=${rpcUrl}`
      );
      content = content.replace(
        /NEXT_PUBLIC_BLOCK_EXPLORER=.*/,
        `NEXT_PUBLIC_BLOCK_EXPLORER=${explorerUrl}`
      );
      fs.writeFileSync(p, content);
      console.log(`Updated environment variables in ${file}`);
    }
  }

  // 3. Contract Verification
  if (hre.network.name !== "hardhat" && hre.network.name !== "localhost") {
    console.log("\nWaiting for block confirmations before verifying...");
    try {
      if (deployTx) {
        await deployTx.wait(3);
      }
      console.log("Attempting automated contract verification...");
      await hre.run("verify:verify", {
        address: deployedAddress,
        constructorArguments: [],
      });
      console.log("✅ Contract verified successfully on explorer!");
    } catch (verifyError: any) {
      console.warn("Automated verification notice:", verifyError?.message || verifyError);
      console.log("Generating flattened source file for manual explorer verification fallback...");
      try {
        const flattened = await hre.run("flatten:get-flattened-sources", {
          files: ["contracts/Booklio.sol"],
        });
        fs.writeFileSync(path.join(rootDir, "contracts", "Booklio_flattened.sol"), flattened);
        console.log("Saved flattened contract to contracts/Booklio_flattened.sol");
      } catch (e) {
        // ignore
      }
    }
  }

  console.log("\n=========================================");
  console.log(`Booklio is live and ready on Botchain (${isMainnet ? "Mainnet" : "Testnet"})!`);
  console.log("=========================================");
}

main().catch((error) => {
  console.error("Deployment failed:", error);
  process.exitCode = 1;
});
